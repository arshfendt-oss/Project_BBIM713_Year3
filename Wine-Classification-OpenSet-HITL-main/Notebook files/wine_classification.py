"""##**Balanced sampling and train/test construction**"""

def balanced_class_sample(
    df,
    classes,
    target_col,
    max_records,
    seed=42
):

    frames = []

    for cls in tqdm(classes):

        group = df[
            df[target_col] == cls
        ]

        n = min(
            len(group),
            max_records
        )

        sample = group.sample(
            n=n,
            random_state=seed
        )

        frames.append(sample)

    return pd.concat(
        frames,
        ignore_index=True
    )


